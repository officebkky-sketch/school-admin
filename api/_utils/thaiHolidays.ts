/**
 * ดึงข้อมูลเวลาประเทศไทย (Asia/Bangkok) และสถานะวันหยุด
 * @param dateObj วันที่ที่ต้องการตรวจสอบ (หากไม่ระบุจะใช้วันที่ปัจจุบันตามเวลาประเทศไทย)
 */
export function getThaiDateInfo(dateObj?: Date | string): ThaiHolidayInfo {
  let targetDate: Date;
  if (!dateObj) {
    targetDate = new Date();
  } else if (typeof dateObj === 'string') {
    targetDate = new Date(dateObj.includes('T') ? dateObj : `${dateObj}T00:00:00+07:00`);
  } else {
    targetDate = dateObj;
  }

  // แปลงเป็นวันที่ตามเวลาท้องถิ่น Asia/Bangkok
  const bangkokDateStr = targetDate.toLocaleDateString('en-CA', { timeZone: 'Asia/Bangkok' }); // คืนค่า YYYY-MM-DD
  const [yearStr, monthStr, dayStr] = bangkokDateStr.split('-');
  const year = parseInt(yearStr, 10);
  const month = parseInt(monthStr, 10);
  const day = parseInt(dayStr, 10);

  // คำนวณวันในสัปดาห์ (0 = อาทิตย์, ..., 6 = เสาร์)
  const bkkDate = new Date(targetDate.toLocaleString('en-US', { timeZone: 'Asia/Bangkok' }));
  const dayOfWeek = bkkDate.getDay();

  const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;
  const isoDateStr = bangkokDateStr;
  const holidayName = THAI_PUBLIC_HOLIDAYS[isoDateStr];
  const isHoliday = !!holidayName;
  const isWorkingDay = !isWeekend && !isHoliday;

  const thaiYear = year + 543;
  const thaiMonthName = THAI_MONTHS[month - 1] || '';
  const thaiDateStr = `${day} ${thaiMonthName} ${thaiYear}`;

  return {
    isHoliday,
    holidayName,
    isWeekend,
    isWorkingDay,
    thaiDateStr,
    isoDateStr,
    dayOfWeek
  };
}

/**
 * ตรวจสอบว่าวันที่ระบุเป็นวันหยุดราชการไทยหรือไม่
 */
export function isThaiPublicHoliday(dateObj?: Date | string): { isHoliday: boolean; holidayName?: string } {
  const info = getThaiDateInfo(dateObj);
  return {
    isHoliday: info.isHoliday,
    holidayName: info.holidayName
  };
}

/**
 * ตรวจสอบว่าวันที่ระบุเป็นวันหยุด (เสาร์-อาทิตย์ หรือวันหยุดนักขัตฤกษ์) หรือไม่
 */
export function isNonWorkingDay(dateObj?: Date | string): { isNonWorking: boolean; reason?: string } {
  const info = getThaiDateInfo(dateObj);
  if (info.isWeekend) {
    const dayNames = ['วันอาทิตย์', 'วันจันทร์', 'วันอังคาร', 'วันพุธ', 'วันพฤหัสบดี', 'วันศุกร์', 'วันเสาร์'];
    return {
      isNonWorking: true,
      reason: `วันหยุดสุดสัปดาห์ (${dayNames[info.dayOfWeek]})`
    };
  }
  if (info.isHoliday) {
    return {
      isNonWorking: true,
      reason: `วันหยุดราชการ (${info.holidayName})`
    };
  }
  return { isNonWorking: false };
}
